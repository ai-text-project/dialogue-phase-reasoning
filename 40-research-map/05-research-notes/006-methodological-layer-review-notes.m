## Review Policy

The current Working Map (005) should not be revised solely on the basis of single supporting Cases.

Instead, candidate dimensions should remain documented here until repeated observations demonstrate comparable stability.

Accordingly:

- 005 records the current working interpretation.
- 006 records future review candidates.

This separation preserves both methodological continuity and formation history.

